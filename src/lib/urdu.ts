const ARABIC_RE = /[؀-ۿ]/;
const KEYS = Object.keys(MAP).sort((a, b) => b.length - a.length);
const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const WORD_RE = new RegExp(`(?<![\\u0600-\\u06FF])(?:${KEYS.map(escapeRe).join("|")})(?![\\u0600-\\u06FF])`, "g");

const DIGITS: Record<string, string> = { "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4", "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9", "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4", "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9" };

export function hasUrduScript(text: string): boolean {
  return ARABIC_RE.test(text);
}

/** Converts Urdu-script text to Roman Urdu (known vocabulary only) and normalises Urdu digits / punctuation. */
export function urduToRoman(text: string): string {
  if (!ARABIC_RE.test(text) && !/[۰-۹٠-٩]/.test(text)) return text;
  return text
    .replace(/[ً-ٰٟ‌‍]/g, "") // diacritics / zero-width joiners
    .replace(/[۰-۹٠-٩]/g, (d) => DIGITS[d] ?? d)
    .replace(/[؟]/g, "?")
    .replace(/[،]/g, ",")
    .replace(/ك/g, "ک") // Arabic kaf -> Urdu kaf
    .replace(/ي/g, "ی") // Arabic yeh -> Urdu yeh
    .replace(WORD_RE, (m) => ` ${MAP[m]} `)
    .replace(/\s+/g, " ")
    .trim();
}
